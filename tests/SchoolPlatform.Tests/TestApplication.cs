using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Mvc.Testing;
using Microsoft.Extensions.Configuration;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using SchoolPlatform.Host.IdentityAccess;
using SchoolPlatform.Host.SchoolData;

namespace SchoolPlatform.Tests;

public sealed class TestApplication(string environment = "Development",
    Dictionary<string, string?>? configuration = null, Action<IServiceCollection>? configureServices = null) : WebApplicationFactory<Program>
{
    protected override void ConfigureWebHost(IWebHostBuilder builder)
    {
        builder.UseEnvironment(environment);
        builder.ConfigureServices(services => configureServices?.Invoke(services));
        builder.ConfigureAppConfiguration((_, config) => config.AddInMemoryCollection(
            new Dictionary<string, string?>
            {
                ["ConnectionStrings:SchoolDatabase"] = "Server=localhost;Database=SchoolPlatform_Unused;Integrated Security=true;Encrypt=true;TrustServerCertificate=true",
                ["Logging:LogLevel:Default"] = "Warning"
            }.Concat(configuration ?? []).GroupBy(x => x.Key).ToDictionary(x => x.Key, x => x.Last().Value)));
    }

    public HttpClient Browser() => CreateClient(new WebApplicationFactoryClientOptions
    {
        AllowAutoRedirect = false, HandleCookies = true, BaseAddress = new Uri("https://localhost")
    });

    /// <summary>
    /// Migrates both contexts only after proving they point at the random catalog generated by this fixture.
    /// Never touches the development or a caller-supplied database.
    /// </summary>
    public async Task MigrateOwnedDatabaseAsync(string database)
    {
        await using var scope = Services.CreateAsyncScope();
        var identity = scope.ServiceProvider.GetRequiredService<IdentityDbContext>();
        var school = scope.ServiceProvider.GetRequiredService<SchoolDbContext>();
        if (!System.Text.RegularExpressions.Regex.IsMatch(database, "^SchoolPlatform_Test_[a-f0-9]{32}$") ||
            identity.Database.GetDbConnection().Database != database || school.Database.GetDbConnection().Database != database)
            throw new InvalidOperationException("The test host is not bound to its generated database; refusing to migrate.");
        await identity.Database.MigrateAsync();
        await school.Database.MigrateAsync();
    }
}
